import assert from 'node:assert/strict';
import { createPauseSession } from './lib/pause-session.js';
let now = 10, hidden = false, current = true, resumes = 0, suspends = 0;
const clock = { now: () => now, hidden: () => hidden, current: () => current };
const context = { suspend: async () => { suspends++; }, resume: async () => { resumes++; } };
let state = createPauseSession(context, 'snapshot', clock);
state.countdown(); assert.equal(state.deadline, 13);
now = 20; assert.equal(await state.resume(), 10); assert.equal(resumes, 1);
assert.equal(await state.resume(), null, 'duplicate resume is ignored');
state = createPauseSession(context, 'snapshot', clock);
hidden = true; state.countdown(); assert.equal(state.deadline, 0);
assert.equal(await state.resume(), null); assert.equal(state.busy, false); assert.equal(suspends, 3);
hidden = false;
let finish;
context.resume = () => new Promise(resolve => finish = resolve);
state = createPauseSession(context, 'snapshot', clock);
const resuming = state.resume(); await Promise.resolve();
current = false; finish();
assert.equal(await resuming, null, 'late audio completion cannot resume a replaced pause');
current = true;
context.resume = async () => { throw new Error('resume failed'); };
state = createPauseSession(context, 'snapshot', clock); state.countdown();
await assert.rejects(state.resume(), /resume failed/);
assert.equal(state.busy, false); assert.equal(state.deadline, 0);
context.suspend = async () => { throw new Error('suspend failed'); };
state = createPauseSession(context, 'snapshot', clock);
await assert.rejects(state.resume(), /suspend failed/); assert.equal(state.busy, false);
